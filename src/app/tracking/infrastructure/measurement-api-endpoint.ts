import { HttpClient } from '@angular/common/http';
import { Observable, catchError, map } from 'rxjs';
import { BaseApiEndpoint } from '../../shared/infrastructure/base-api-endpoint';
import { environment } from '../../../environments/environment';
import { Measurement } from '../domain/model/measurement.entity';
import { MonitoredMetric } from '../domain/model/monitored-metric';
import { MeasurementAssembler } from './measurement-assembler';
import { MeasurementResource, MeasurementsResponse } from './tracking-response';
import { DeviceTarget } from './device-target';
import { TelemetryPeriod } from './telemetry-period';
import { targetPath, periodParams } from './telemetry-request';

const laboratoriesEndpointUrl = `${environment.serverBasePath}${environment.laboratoryLabsEndpointPath}`;

/**
 * Endpoint responsible for retrieving IoT telemetry measurements.
 *
 * Provides access to environmental readings generated by:
 * - Environmental devices.
 * - Container monitoring devices.
 *
 * The endpoint converts API resources into domain Measurement entities
 * using the corresponding assembler.
 */
export class MeasurementApiEndpoint extends BaseApiEndpoint<
  Measurement,
  MeasurementResource,
  MeasurementsResponse,
  MeasurementAssembler
> {
  constructor(http: HttpClient) {
    super(http, laboratoriesEndpointUrl, new MeasurementAssembler());
  }

  /**
   * Retrieves measurements from an IoT device during a selected period.
   *
   * @param target Device or environment identifier.
   * @param period Requested telemetry period.
   * @param metric Optional metric filter.
   * @returns Observable containing measurement domain entities.
   */
  getMeasurements(
    target: DeviceTarget,
    period: TelemetryPeriod,
    metric?: MonitoredMetric | null,
  ): Observable<Measurement[]> {
    const url = `${targetPath(this.endpointUrl, target)}${environment.trackingTelemetryMeasurementsEndpointPath}`;
    return this.http.get<MeasurementResource[]>(url, { params: periodParams(period, metric) }).pipe(
      map((resources) =>
        resources.map((resource) => this.assembler.toEntityFromResource(resource)),
      ),
      catchError(this.handleError('Failed to fetch the readings')),
    );
  }
}
